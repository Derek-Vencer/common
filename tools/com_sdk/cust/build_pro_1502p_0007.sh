#!/bin/bash

TARGET_LIST="best1502p"
CHIPID="best1502p"
COMMAND=$1
set -e

APP_CUSTOMER_CFG="IGNORE_POWER_ON_KEY_DURING_BOOT_UP=1 IS_AUTOPOWEROFF_ENABLED=0 APP_TRACE_RX_ENABLE=1 APP_RX_API_ENABLE=1 AUDIO_DEBUG_CMD=0 \
                 TRACE_BUF_SIZE=40*1024 USE_TRACE_ID=0"

BLE_CFG="BLE=1 GATT_OVER_BR_EDR=0"

OTA_CFG="BES_OTA=1 OTA_BIN_COMPRESSED=1"

FREEMAN_CFG="POWER_ON_ENTER_FREEMAN_PAIRING_ENABLED=1 FREEMAN_ENABLED_STERO=1"

SPEECH_1MIC_CFG="SPEECH_TX_DC_FILTER=1 SPEECH_TX_1MIC_NS=1 SPEECH_TX_EQ=1 SPEECH_RX_EQ=1 SPEECH_RX_NS2FLOAT=1"

DECODE_DECODER_CFG="A2DP_AAC_ON=1 A2DP_LDAC_ON=1 A2DP_LHDC_ON=0 A2DP_LHDC_V3=0 A2DP_LHDCV5_ON=0 AAC_IN_ROM=1 CVSD_IN_ROM=1"
                    
CP_CFG="A2DP_CP_ACCEL=1 SCO_CP_ACCEL=1 CHIP_HAS_CP=1"

ANC_CFG="ANC_ENABLE=1 ANC_ASSIST_ENABLED=1 TOTA_v2=1"

SYS_CFG=" ALLOW_WARNING=1 BES_LIB_DIR=lib/bes/best1502p/PRO_0007"

build_ota_copy_cmd="make T=prod_test/ota_copy -j64 CHIP=best1502p DEBUG=1 BES_LIB_DIR=lib/bes/best1502p/PRO_0007"
build_app_cmd="make T=best1502p -j64 DEBUG=1"

if [[ "$COMMAND" == "clean" ]];
then
    $build_app_cmd clean
    $build_ota_copy_cmd clean
    echo "clean end"
elif [[ "$COMMAND" == "gen_lib" ]];
then
    $build_app_cmd $APP_CUSTOMER_CFG $BLE_CFG $OTA_CFG $FREEMAN_CFG $SPEECH_1MIC_CFG $DECODE_DECODER_CFG $CP_CFG $ANC_CFG $SYS_CFG GEN_LIB=1
    $build_ota_copy_cmd GEN_LIB=1
elif [[ "$COMMAND" == 'lst' ]];
then
    $build_app_cmd $APP_CUSTOMER_CFG $BLE_CFG $OTA_CFG $FREEMAN_CFG $SPEECH_1MIC_CFG $DECODE_DECODER_CFG $CP_CFG $SYS_CFG $ANC_CFG lst all
    echo "lst build end"
else
    $build_app_cmd $APP_CUSTOMER_CFG $BLE_CFG $OTA_CFG $FREEMAN_CFG $SPEECH_1MIC_CFG $DECODE_DECODER_CFG $CP_CFG $SYS_CFG $ANC_CFG
    $build_ota_copy_cmd
    echo "normal build"
    echo " "
fi